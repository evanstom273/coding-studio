/**
 * TypeScript / JavaScript entry points. The entry function is exported and a small launcher
 * module next to it starts it:
 *   - browser: runs when the page loads (the preview, Vite); a React component is rendered
 *     into #root instead of being called;
 *   - node: runs as a command-line program (tsx / node).
 * Async functions are awaited at the top level of the launcher (ES modules), so errors surface.
 */
import type { EntryPointSupport } from '@cs/language-sdk';

export const typescriptEntry: EntryPointSupport = {
  hosts: [
    { id: 'browser', label: 'Browser page', description: 'Starts when the page loads: the Preview, or a Vite / static site. A React component is rendered into #root.' },
    { id: 'node', label: 'Node.js program', description: 'Starts when run from a terminal or CI: npx tsx <launcher> (TypeScript) or node <launcher> (JavaScript).' },
  ],
  defaultHost: () => 'browser',
  apply(module, req, ctx) {
    const mode = module.settings.output === 'js' ? 'js' : 'ts';
    const name = req.fn.name;
    const base = module.path.split('/').pop()!;
    const dir = module.path.includes('/') ? module.path.slice(0, module.path.lastIndexOf('/') + 1) : '';
    const members = module.members.map((m) => (m.k === 'function' && m.name === name ? { ...m, exported: true } : m));
    const nl = '\n';
    const header = ctx.settings.header ? [`// Program entry point, generated by Coding Studio: starts ${name}() from "${module.name}".`, ''] : [];
    if (req.fn.component) {
      if (req.host !== 'browser') return { module: { ...module, members }, diagnostics: [{ severity: 'error', code: 'E_ENTRY_HOST', message: `${name} is a React component, so it can only start in a browser page.`, functionId: req.fn.id }] };
      const lines = [...header, "import { createRoot } from 'react-dom/client';", `import { ${name} } from './${base}';`, '', "const container = document.getElementById('root') ?? document.body.appendChild(document.createElement('div'));", `createRoot(container).render(<${name} />);`];
      const path = `${dir}${base}.entry.${mode}x`;
      return {
        module: { ...module, members },
        files: [{ path, content: lines.join(nl) + nl, sourceMap: [{ line: lines.length, scriptId: module.scriptId, graphId: req.fn.graph.id }] }],
        instructions: [`${path} renders <${name} /> into #root. The Preview uses it when index.html doesn't name a script of its own; in a Vite project point index.html at it: <script type="module" src="/${path}"></script>. Needs react and react-dom in package.json.`],
      };
    }
    const call = `${req.isAsync ? 'await ' : ''}${name}();`;
    const lines = [...header, `import { ${name} } from './${base}';`, '', call];
    const path = `${dir}${base}.entry.${mode}`;
    const run = req.host === 'node' ? (mode === 'ts' ? `npx tsx ${path}` : `node ${path}`) : `the Preview, or <script type="module" src="/${path}"></script> in index.html`;
    return {
      module: { ...module, members },
      files: [{ path, content: lines.join(nl) + nl, sourceMap: [{ line: lines.length, scriptId: module.scriptId, graphId: req.fn.graph.id }] }],
      instructions: [`${path} starts ${name}()${req.isAsync ? ' and waits for it' : ''}. Run it with ${run}.`],
    };
  },
};
